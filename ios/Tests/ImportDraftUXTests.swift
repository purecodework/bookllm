import XCTest
import TranslationCore
@testable import BookLLM

final class ImportDraftUXTests: XCTestCase {
    private func folder() throws -> URL {
        let value = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: value, withIntermediateDirectories: true)
        addTeardownBlock { try? FileManager.default.removeItem(at: value) }
        return value
    }
    @MainActor func testPasteDraftRestoresExactInputAndStableIdentity() throws {
        let url = try folder().appendingPathComponent("paste.json")
        let first = PasteDraftCoordinator(storageURL: url)
        first.open(); first.setTitle("  暂存名称  "); first.setText("First paragraph.\n\n第二段。\n")
        XCTAssertFalse(first.isSaved)
        XCTAssertTrue(first.flush())
        XCTAssertTrue(first.isSaved)
        let restored = PasteDraftCoordinator(storageURL: url)
        XCTAssertEqual(restored.draft, first.draft)
        XCTAssertTrue(restored.hasDraft)
    }
    @MainActor func testUnreadablePasteDraftCannotBeOverwrittenWithoutExplicitDiscard() throws {
        let url = try folder().appendingPathComponent("paste.json")
        let original = Data("not a valid draft".utf8)
        try original.write(to: url)
        let value = PasteDraftCoordinator(storageURL: url)
        XCTAssertNotNil(value.loadError)
        value.open(); value.setText("replacement")
        XCTAssertFalse(value.flush())
        XCTAssertEqual(try Data(contentsOf: url), original)
        XCTAssertTrue(value.discard())
        value.open(); value.setText("replacement")
        XCTAssertTrue(value.flush())
        XCTAssertEqual(PasteDraftCoordinator(storageURL: url).draft?.text, "replacement")
    }
    @MainActor func testPasteWriteFailureRetainsInputAndAllowsRetry() throws {
        let root = try folder(), blocked = root.appendingPathComponent("blocked")
        try Data("file".utf8).write(to: blocked)
        let value = PasteDraftCoordinator(storageURL: blocked.appendingPathComponent("paste.json"))
        value.open(); value.setText("Keep this input.")
        let id = value.draft?.id
        XCTAssertFalse(value.flush())
        XCTAssertNotNil(value.saveError)
        XCTAssertFalse(value.isSaved)
        XCTAssertEqual(value.draft?.text, "Keep this input.")
        try FileManager.default.removeItem(at: blocked)
        XCTAssertTrue(value.flush())
        XCTAssertNil(value.saveError)
        XCTAssertEqual(PasteDraftCoordinator(storageURL: value.storageURL).draft?.id, id)
    }
    @MainActor func testPasteLibraryFailureKeepsDraftAndSuccessClearsIt() async throws {
        let root = try folder(), libraryURL = root.appendingPathComponent("studio.json")
        let store = StudioStore(storageURL: libraryURL)
        let value = PasteDraftCoordinator(storageURL: root.appendingPathComponent("paste.json"))
        value.open(); value.setText("A new manuscript.")
        XCTAssertTrue(value.flush())
        let id = try XCTUnwrap(value.draft?.id)
        try FileManager.default.createDirectory(at: libraryURL, withIntermediateDirectories: false)
        do { _ = try await value.addToLibrary(studio: store); XCTFail("Disk failure ignored") } catch { }
        XCTAssertEqual(value.draft?.id, id)
        XCTAssertEqual(PasteDraftCoordinator(storageURL: value.storageURL).draft?.text, "A new manuscript.")
        XCTAssertNil(store.job(id))
        try FileManager.default.removeItem(at: libraryURL)
        let added = try await value.addToLibrary(studio: store)
        XCTAssertEqual(added, id)
        XCTAssertEqual(store.job(id)?.title, "未命名")
        XCTAssertNil(value.draft)
        XCTAssertFalse(FileManager.default.fileExists(atPath: value.storageURL.path))
        XCTAssertEqual(StudioStore(storageURL: libraryURL).job(id)?.source, "A new manuscript.")
    }
    @MainActor func testRetainedPasteAfterCommitDoesNotCreateDuplicateBook() async throws {
        let root = try folder(), url = root.appendingPathComponent("paste.json")
        let value = PasteDraftCoordinator(storageURL: url)
        value.open(); value.setTitle("Saved manuscript"); value.setText("Durable content.")
        XCTAssertTrue(value.flush())
        let retained = try Data(contentsOf: url)
        let store = StudioStore(storageURL: root.appendingPathComponent("studio.json"))
        let id = try await value.addToLibrary(studio: store)
        // Reproduce process exit after the library write but before draft cleanup.
        try retained.write(to: url)
        let recovered = PasteDraftCoordinator(storageURL: url)
        let recoveredID = try await recovered.addToLibrary(studio: store)
        XCTAssertEqual(recoveredID, id)
        XCTAssertEqual(store.jobs.filter { $0.id == id }.count, 1)
        XCTAssertNil(recovered.draft)
    }
    @MainActor func testCommittedPasteReconcilesBeforeDisplayingLibrary() async throws {
        let root = try folder(), url = root.appendingPathComponent("paste.json")
        let value = PasteDraftCoordinator(storageURL: url)
        value.open(); value.setText("Saved content."); XCTAssertTrue(value.flush())
        let retained = try Data(contentsOf: url)
        let store = StudioStore(storageURL: root.appendingPathComponent("studio.json"))
        _ = try await value.addToLibrary(studio: store)
        try retained.write(to: url)
        let recovered = PasteDraftCoordinator(storageURL: url)
        recovered.reconcile(studio: store)
        XCTAssertFalse(recovered.hasDraft)
        XCTAssertEqual(store.jobs.count, 1)
        XCTAssertFalse(FileManager.default.fileExists(atPath: url.path))
    }
    @MainActor func testImportSaveFailureRetainsSourceAndSuccessReplacesPendingDraft() async throws {
        let root = try folder(), source = root.appendingPathComponent("original.txt")
        try Data("Original manuscript.".utf8).write(to: source)
        let importRoot = root.appendingPathComponent("imports")
        let draft = try ImportFiles.copy(source, rootURL: importRoot)
        let importer = ImportCoordinator(rootURL: importRoot)
        let imported = ImportedText(title: draft.title, text: "Original manuscript.", format: "TXT", sourceDocumentID: draft.id)
        importer.result = imported; importer.phase = .reviewing; importer.presented = true
        let libraryURL = root.appendingPathComponent("studio.json"), store = StudioStore(storageURL: libraryURL)
        try FileManager.default.createDirectory(at: libraryURL, withIntermediateDirectories: false)
        do { try await importer.accept(imported, studio: store); XCTFail("Disk failure ignored") } catch { }
        XCTAssertEqual(importer.draft?.id, draft.id)
        XCTAssertTrue(importer.presented)
        XCTAssertFalse(importer.needsOCRReview)
        XCTAssertNotNil(importer.error)
        XCTAssertNotNil(ImportFiles.pending(rootURL: importRoot))
        XCTAssertTrue(FileManager.default.fileExists(atPath: draft.url(rootURL: importRoot).path))
        try FileManager.default.removeItem(at: libraryURL)
        try await importer.accept(imported, studio: store)
        XCTAssertEqual(importer.jobID, draft.id)
        XCTAssertNil(importer.draft)
        XCTAssertFalse(importer.presented)
        XCTAssertNil(ImportFiles.pending(rootURL: importRoot))
        XCTAssertEqual(StudioStore(storageURL: libraryURL).job(draft.id)?.sourceDocumentID, draft.id)
        XCTAssertTrue(FileManager.default.fileExists(atPath: draft.url(rootURL: importRoot).path))
    }
    @MainActor func testUnreadableImportRecordBlocksNewImportUntilExplicitDiscard() throws {
        let root = try folder(), source = root.appendingPathComponent("original.txt")
        try Data("Original manuscript.".utf8).write(to: source)
        let importRoot = root.appendingPathComponent("imports")
        let draft = try ImportFiles.copy(source, rootURL: importRoot)
        let page = OCRPage(number: 1, text: "Retained recognition.", usedOCR: true)
        try ImportFiles.save(page, draft: draft, rootURL: importRoot)
        let index = importRoot.appendingPathComponent("pending.json"), corrupted = Data("broken record".utf8)
        try corrupted.write(to: index)
        let importer = ImportCoordinator(rootURL: importRoot)
        XCTAssertNotNil(importer.recoveryError)
        XCTAssertTrue(importer.hasPending)
        let store = StudioStore(storageURL: root.appendingPathComponent("studio.json"))
        importer.resume(studio: store)
        XCTAssertTrue(importer.presented)
        let nextSource = root.appendingPathComponent("next.txt")
        try Data("New manuscript.".utf8).write(to: nextSource)
        importer.start(nextSource, studio: store)
        XCTAssertEqual(try Data(contentsOf: index), corrupted)
        XCTAssertTrue(store.jobs.isEmpty)
        XCTAssertTrue(importer.discard())
        XCTAssertNil(importer.recoveryError)
        XCTAssertFalse(importer.hasPending)
        XCTAssertFalse(FileManager.default.fileExists(atPath: index.path))
        XCTAssertTrue(FileManager.default.fileExists(atPath: draft.url(rootURL: importRoot).path))
        XCTAssertEqual(ImportFiles.cached(draft, rootURL: importRoot)[1]?.text, page.text)
    }
    @MainActor func testRecoveryRetryReadsRestoredRecordWithoutReplacingSource() async throws {
        let root = try folder(), source = root.appendingPathComponent("original.txt")
        try Data("Original manuscript.".utf8).write(to: source)
        let importRoot = root.appendingPathComponent("imports"), draft = try ImportFiles.copy(source, rootURL: importRoot)
        let index = importRoot.appendingPathComponent("pending.json"), validRecord = try Data(contentsOf: index)
        try Data("broken record".utf8).write(to: index)
        let importer = ImportCoordinator(rootURL: importRoot)
        XCTAssertNotNil(importer.recoveryError)
        try validRecord.write(to: index)
        let libraryURL = root.appendingPathComponent("studio.json"), store = StudioStore(storageURL: libraryURL)
        try FileManager.default.createDirectory(at: libraryURL, withIntermediateDirectories: false)
        importer.retryRecovery(studio: store)
        let deadline = ContinuousClock.now + .seconds(5)
        while (importer.result == nil || importer.accepting) && ContinuousClock.now < deadline { try await Task.sleep(for: .milliseconds(20)) }
        XCTAssertNil(importer.recoveryError)
        XCTAssertEqual(importer.draft?.id, draft.id)
        XCTAssertEqual(importer.result?.text, "Original manuscript.")
        XCTAssertEqual(try Data(contentsOf: index), validRecord)
        XCTAssertFalse(importer.needsOCRReview)
        importer.resume(studio: store)
        XCTAssertEqual(importer.phase, .reviewing)
        XCTAssertEqual(importer.result?.text, "Original manuscript.")
    }
    @MainActor func testMissingSourceRecordBlocksOverwriteAndKeepsRecord() throws {
        let root = try folder(), source = root.appendingPathComponent("original.txt")
        try Data("Original manuscript.".utf8).write(to: source)
        let importRoot = root.appendingPathComponent("imports"), draft = try ImportFiles.copy(source, rootURL: importRoot)
        let index = importRoot.appendingPathComponent("pending.json"), original = try Data(contentsOf: index)
        try FileManager.default.removeItem(at: draft.url(rootURL: importRoot))
        let importer = ImportCoordinator(rootURL: importRoot)
        XCTAssertNotNil(importer.recoveryError)
        let store = StudioStore(storageURL: root.appendingPathComponent("studio.json"))
        importer.start(source, studio: store)
        XCTAssertEqual(try Data(contentsOf: index), original)
        XCTAssertTrue(importer.hasPending)
        XCTAssertTrue(store.jobs.isEmpty)
    }
}
